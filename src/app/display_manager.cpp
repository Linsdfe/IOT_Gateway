DisplayManager::DisplayManager()
    : mgr_(nullptr)
    , running_(false)
    , fbFd_(-1)
    , fbMem_(nullptr)
    , fbWidth_(0)
    , fbHeight_(0)
    , fbBpp_(0)
    , fbLineLen_(0)
{
}

DisplayManager::~DisplayManager()
{
    stop();
}

bool DisplayManager::init(const Config &cfg)
{
    cfg_ = cfg;
    if (!cfg_.enabled) {
        LOG_I("Display", "disabled, skip init");
        return true;
    }

    /* 打开 Framebuffer 设备，需要读写权限 */
    fbFd_ = open(cfg_.fbDevice.c_str(), O_RDWR);
    if (fbFd_ < 0) {
        LOG_E("Display", "open %s failed", cfg_.fbDevice.c_str());
        return false;
    }

    /* 通过 ioctl 获取屏幕可变参数（分辨率、色深等） */
    struct fb_var_screeninfo vinfo;
    if (ioctl(fbFd_, FBIOGET_VSCREENINFO, &vinfo) < 0) {
        LOG_E("Display", "get vinfo failed");
        close(fbFd_);
        fbFd_ = -1;
        return false;
    }

    fbWidth_ = vinfo.xres;
    fbHeight_ = vinfo.yres;
    fbBpp_ = vinfo.bits_per_pixel;
    fbLineLen_ = fbWidth_ * fbBpp_ / 8;

    /* mmap 将 Framebuffer 显存映射到用户空间，
     * 之后可直接通过指针操作像素，无需 write/ioctl */
    size_t screensize = fbWidth_ * fbHeight_ * fbBpp_ / 8;
    fbMem_ = mmap(nullptr, screensize, PROT_READ | PROT_WRITE,
                  MAP_SHARED, fbFd_, 0);
    if (fbMem_ == MAP_FAILED) {
        LOG_E("Display", "mmap failed");
        close(fbFd_);
        fbFd_ = -1;
        fbMem_ = nullptr;
        return false;
    }

    LOG_I("Display", "init OK (%dx%d, %dbpp)", fbWidth_, fbHeight_, fbBpp_);
    return true;
}

bool DisplayManager::start(DataManager *mgr)
{
    if (!cfg_.enabled) return true;
    mgr_ = mgr;
    running_ = true;
    displayThread_ = std::thread(&DisplayManager::displayLoop, this);
    LOG_I("Display", "started");
    return true;
}

void DisplayManager::stop()
{
    running_ = false;
    if (displayThread_.joinable())
        displayThread_.join();
    /* 释放 mmap 映射和文件描述符 */
    if (fbMem_) {
        munmap(fbMem_, fbWidth_ * fbHeight_ * fbBpp_ / 8);
        fbMem_ = nullptr;
    }
    if (fbFd_ >= 0) {
        close(fbFd_);
        fbFd_ = -1;
    }
    LOG_I("Display", "stopped");
}

void DisplayManager::fillRect(int x, int y, int w, int h, uint32_t color)
{
    if (!fbMem_) return;
    uint32_t *p = (uint32_t *)fbMem_;
    for (int j = y; j < y + h && j < fbHeight_; j++) {
        for (int i = x; i < x + w && i < fbWidth_; i++) {
            p[j * fbWidth_ + i] = color;
        }
    }
}

void DisplayManager::drawText(int x, int y, const char *text, uint32_t color)
{
    if (!fbMem_) return;
    uint32_t *p = (uint32_t *)fbMem_;
    int cx = x;
    while (*text) {
        /* 将 ASCII 字符映射到字体表索引（ASCII 32~127 → 索引 0~95） */
        int idx = (unsigned char)*text;
        if (idx < 32 || idx > 127) idx = 32; /* 非法字符显示为空格 */
        idx -= 32;

        /* 逐列扫描：5 列 × 7 行，每列的位图数据按位展开 */
        for (int col = 0; col < 5; col++) {
            uint8_t line = FONT_5X7[idx][col];
            for (int row = 0; row < 7; row++) {
                if (line & (1 << row)) {
                    int px = cx + col;
                    int py = y + row;
                    if (px >= 0 && px < fbWidth_ && py >= 0 && py < fbHeight_)
                        p[py * fbWidth_ + px] = color;
                }
            }
        }
        cx += 6; /* 5 像素字宽 + 1 像素间距 */
        text++;
    }
}

void DisplayManager::updateDisplay(const SensorData &data)
{
    if (!fbMem_) return;

    /* 深蓝色背景 (0x1A1A2E)，营造科技感 */
    fillRect(0, 0, fbWidth_, fbHeight_, 0x1A1A2E);

    /* 标题：青色 (0x00D4FF) */
    drawText(10, 10, "IoT Gateway", 0x00D4FF);

    char buf[64];

    /* 温度：白色 (0xFFFFFF) */
    snprintf(buf, sizeof(buf), "Temp: %.1f C", data.temperature);
    drawText(10, 40, buf, 0xFFFFFF);

    /* 湿度：绿色 (0x00FF88) */
    snprintf(buf, sizeof(buf), "Humi: %.1f %%", data.humidity);
    drawText(10, 60, buf, 0x00FF88);

    /* 光照：橙色 (0xFFAA00) */
    snprintf(buf, sizeof(buf), "Light: %.1f lux", data.light);
    drawText(10, 80, buf, 0xFFAA00);
}

void DisplayManager::displayLoop()
{
    while (running_) {
        if (mgr_) {
            SensorData data = mgr_->getLatestData();
            if (data.valid) {
                updateDisplay(data);
            }
        }
        /* 200ms 刷新间隔，平衡流畅度与 CPU 占用 */
        usleep(200000);
    }
}
